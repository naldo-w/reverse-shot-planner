export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string

export function makeTranslate(lang: Lang): Translate {
  const table = MESSAGES[lang]
  return (key, vars) =>
    table[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars?.[k] ?? `{${k}}`))
}

